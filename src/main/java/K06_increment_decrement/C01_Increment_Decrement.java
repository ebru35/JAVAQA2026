package K06_increment_decrement;

public class C01_Increment_Decrement {

    public static void main(String[] args) {

        int sayi = 20 ;


        sayi *= 2 ;

        System.out.println("14.satirda sayi : " + sayi );




        sayi -= 5 ;

        System.out.println("22.satirda sayi : " + sayi );

        sayi = sayi / 5  ;

        System.out.println("29.satirda sayi : " + sayi );



        sayi = sayi + 1 ;

        System.out.println("36.satirda sayi : " + sayi );



        sayi += 1 ;

        System.out.println("43.satirda sayi : " + sayi );

        sayi++ ;

        System.out.println("50.satirda sayi : " + sayi );
    }
}